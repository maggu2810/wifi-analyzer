"""Build identity from git (docs/decisions/0008-versioning-from-git.md).

Prints the version stamp of a deliverable:
  X.Y.Z                       exactly at tag <prefix>X.Y.Z, clean work tree (a release)
  X.Y.Z-dev.N+gHASH[.dirty]   N commits after the newest <prefix>* tag
  X.Y.Z-dev+gHASH[.dirty]     no <prefix>* tag yet
  X.Y.Z+nogit                 not built from a git work tree

--count prints the number of commits up to HEAD (Android versionCode), 1 without git.
--out FILE --name NS::VAR writes a C++ header 'namespace NS { inline constexpr
std::string_view VAR = "<stamp>"; }' (only when the content changes, so dependents rebuild
only when the stamp changes).

Never fails because of git: build tools call it on every build.
"""

import argparse
import pathlib
import re
import subprocess
import sys


def git(repo: pathlib.Path, *args: str) -> str | None:
    try:
        result = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True,
                                check=False)
    except OSError:
        return None
    return result.stdout.strip() if result.returncode == 0 else None


def stamp(repo: pathlib.Path, prefix: str, version: str) -> str:
    if git(repo, "rev-parse", "--is-inside-work-tree") != "true":
        return f"{version}+nogit"
    described = git(repo, "describe", "--tags", "--long", "--dirty=-dirty", "--abbrev=7",
                    "--match", f"{prefix}[0-9]*")
    if described:
        m = re.fullmatch(rf"{re.escape(prefix)}(.+)-(\d+)-g([0-9a-f]+)(-dirty)?", described)
        if m:
            tag_version, distance, commit, dirty = m.groups()
            if distance == "0" and not dirty and tag_version == version:
                return version
            return f"{version}-dev.{distance}+g{commit}{'.dirty' if dirty else ''}"
    # No matching tag: commit only.
    described = git(repo, "describe", "--always", "--dirty=-dirty", "--abbrev=7",
                    "--match", f"{prefix}[0-9]*")
    m = re.fullmatch(r"([0-9a-f]+)(-dirty)?", described or "")
    if not m:
        return f"{version}+nogit"
    return f"{version}-dev+g{m.group(1)}{'.dirty' if m.group(2) else ''}"


def commit_count(repo: pathlib.Path) -> int:
    if git(repo, "rev-parse", "--is-shallow-repository") == "true":
        print("git_version.py: warning: shallow clone, commit count is wrong", file=sys.stderr)
    count = git(repo, "rev-list", "--count", "HEAD")
    return int(count) if count and count.isdigit() else 1


def write_if_changed(path: pathlib.Path, content: str) -> None:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", type=pathlib.Path,
                        default=pathlib.Path(__file__).resolve().parent.parent)
    parser.add_argument("--prefix", help="tag prefix, e.g. android-v")
    parser.add_argument("--version", help="version from the build files, e.g. 0.3.0")
    parser.add_argument("--count", action="store_true", help="print the commit count")
    parser.add_argument("--out", type=pathlib.Path, help="write a C++ header")
    parser.add_argument("--name", help="qualified constant name for --out, e.g. ns::version")
    args = parser.parse_args()

    if args.count:
        print(commit_count(args.repo))
        return 0
    if not args.prefix or not args.version:
        parser.error("--prefix and --version are required")
    value = stamp(args.repo, args.prefix, args.version)
    if args.out:
        namespace, _, name = (args.name or "").rpartition("::")
        if not namespace or not name:
            parser.error("--out requires --name NAMESPACE::NAME")
        write_if_changed(args.out,
                         "// SPDX-License-Identifier: MIT\n"
                         "// Generated by tools/git_version.py - do not edit.\n"
                         "#pragma once\n\n"
                         "#include <string_view>\n\n"
                         f"namespace {namespace} {{\n"
                         f'inline constexpr std::string_view {name} = "{value}";\n'
                         f"}} // namespace {namespace}\n")
    else:
        print(value)
    return 0


if __name__ == "__main__":
    sys.exit(main())
