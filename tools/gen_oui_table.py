"""Generates the built-in OUI table of libwifianalyze from a curated CSV ("OUI,Name")."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path


def cxx_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--csv", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    entries: dict[int, str] = {}
    for lineno, raw in enumerate(args.csv.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.fullmatch(r"([0-9A-Fa-f]{6})\s*,\s*(.+)", line)
        if not m:
            print(f"error: {args.csv}:{lineno}: expected 'OUI,Name'", file=sys.stderr)
            return 1
        oui = int(m.group(1), 16)
        if oui in entries:
            print(f"error: {args.csv}:{lineno}: duplicate OUI {m.group(1)}", file=sys.stderr)
            return 1
        entries[oui] = m.group(2).strip()

    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/gen_oui_table.py from data/oui-builtin.csv – do not edit.",
        "",
        f"inline constexpr std::array<BuiltinOui, {len(entries)}> builtin_ouis{{{{",
    ]
    lines += [f"    {{0x{oui:06x}U, {cxx_string(name)}}}," for oui, name in sorted(entries.items())]
    lines += ["}};", ""]
    content = "\n".join(lines)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    if not args.out.exists() or args.out.read_text(encoding="utf-8") != content:
        args.out.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
